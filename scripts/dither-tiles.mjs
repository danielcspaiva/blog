// Generates the 1-bit ordered-dither tiles used across the site and writes them
// to src/styles/dither-tiles.css as inline PNG data URIs (custom properties).
//
// The tiles are alpha masks: opaque where a dot is "on", transparent elsewhere.
// CSS paints them with `mask-image` over a solid background-color, so every
// pattern follows the current theme's ink/paper automatically.
//
//   pnpm dither
//
import { writeFile } from "node:fs/promises";
import sharp from "sharp";

const CELL = 2; // CSS px per dither cell — 1px cells shimmer on scroll at DPR 1

const BAYER4 = [
  [0, 8, 2, 10],
  [12, 4, 14, 6],
  [3, 11, 1, 9],
  [15, 7, 13, 5],
];

const BAYER8 = [
  [0, 32, 8, 40, 2, 34, 10, 42],
  [48, 16, 56, 24, 50, 18, 58, 26],
  [12, 44, 4, 36, 14, 46, 6, 38],
  [60, 28, 52, 20, 62, 30, 54, 22],
  [3, 35, 11, 43, 1, 33, 9, 41],
  [51, 19, 59, 27, 49, 17, 57, 25],
  [15, 47, 7, 39, 13, 45, 5, 37],
  [63, 31, 55, 23, 61, 29, 53, 21],
];

/** Render a cols×rows grid of cells; `on(cx, cy)` decides each cell. */
async function tile(cols, rows, on) {
  const w = cols * CELL;
  const h = rows * CELL;
  const buf = Buffer.alloc(w * h * 4);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (on(Math.floor(x / CELL), Math.floor(y / CELL))) {
        buf[(y * w + x) * 4 + 3] = 255;
      }
    }
  }
  const png = await sharp(buf, { raw: { width: w, height: h, channels: 4 } })
    .png({ compressionLevel: 9, palette: true, colours: 2 })
    .toBuffer();
  return {
    w,
    h,
    uri: `url("data:image/png;base64,${png.toString("base64")}")`,
  };
}

const flat = (level) => tile(4, 4, (x, y) => BAYER4[y][x] < level);

// Density ramps 1 → 0 along one axis; eased so the dense end holds a little
// longer and the sparse end trails off.
const ramp = (t) => Math.pow(1 - t, 1.35);
const fadeY = (rows) =>
  tile(
    8,
    rows,
    (x, y) => ramp((y + 0.5) / rows) > (BAYER8[y % 8][x] + 0.5) / 64,
  );
const fadeX = (cols) =>
  tile(
    cols,
    8,
    (x, y) => ramp((x + 0.5) / cols) > (BAYER8[y][x % 8] + 0.5) / 64,
  );

const tiles = {
  "dt-12": await flat(2),
  "dt-25": await flat(4),
  "dt-50": await flat(8),
  "dt-75": await flat(12),
  "dt-fade-y-sm": await fadeY(12), // 24px
  "dt-fade-y-md": await fadeY(32), // 64px
  "dt-fade-y-lg": await fadeY(80), // 160px
  "dt-fade-x": await fadeX(144), // 288px
};

const lines = Object.entries(tiles).map(
  ([name, t]) => `  /* ${t.w}×${t.h} */\n  --${name}: ${t.uri};`,
);

const css = `/* GENERATED by scripts/dither-tiles.mjs — do not edit by hand (run \`pnpm dither\`). */
:root {
${lines.join("\n")}
}
`;

await writeFile(
  new URL("../src/styles/dither-tiles.css", import.meta.url),
  css,
);
